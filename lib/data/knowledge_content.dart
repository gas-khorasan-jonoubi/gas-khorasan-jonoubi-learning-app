enum KnowledgeArea {
  general,
  customers,
  receivables,
  maintenance,
  hse,
  management,
}

extension KnowledgeAreaLabel on KnowledgeArea {
  String get label {
    switch (this) {
      case KnowledgeArea.general:
        return 'عمومی';
      case KnowledgeArea.customers:
        return 'امور مشترکین';
      case KnowledgeArea.receivables:
        return 'وصول مطالبات';
      case KnowledgeArea.maintenance:
        return 'تعمیرات';
      case KnowledgeArea.hse:
        return 'HSE و ایمنی';
      case KnowledgeArea.management:
        return 'مدیریت اداره';
    }
  }
}

